// Regenerates data/blur.ts: a tiny blurred preview of every photo in public/images, shown while the full image loads.
// Run `node scripts/blur.mjs` after adding or replacing a photo
import { readdirSync, writeFileSync } from 'node:fs'
import sharp from 'sharp'

const dir = 'public/images'
// Transparent artwork has no photo to preview
const skip = new Set(['logo.webp'])
const rows = []
for (const file of readdirSync(dir).filter(f => /\.(webp|jpe?g|png)$/i.test(f) && !skip.has(f)).sort()) {
  const buf = await sharp(`${dir}/${file}`).resize(16, 16, { fit: 'inside' }).webp({ quality: 50 }).toBuffer()
  rows.push(`  '/images/${file}': 'data:image/webp;base64,${buf.toString('base64')}',`)
}
writeFileSync('data/blur.ts', `// Generated by scripts/blur.mjs: tiny previews shown blurred while each photo loads
export const blurOf: Record<string, string> = {
${rows.join('\n')}
}
`)
console.log(`${rows.length} previews written to data/blur.ts`)
